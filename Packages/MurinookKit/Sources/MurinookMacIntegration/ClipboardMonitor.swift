import AppKit
import Foundation
import MurinookDomain

public struct ClipboardRepresentationSnapshot: Sendable, Hashable {
    public let typeIdentifier: String
    public let data: Data

    public init(typeIdentifier: String, data: Data) {
        self.typeIdentifier = typeIdentifier
        self.data = data
    }
}

public struct ClipboardItemSnapshot: Sendable, Hashable {
    public let representations: [ClipboardRepresentationSnapshot]
    public let files: [FileReference]

    public init(representations: [ClipboardRepresentationSnapshot], files: [FileReference] = []) {
        self.representations = representations
        self.files = files
    }
}

public struct ClipboardSnapshot: Sendable, Hashable {
    public let changeCount: Int
    public let items: [ClipboardItemSnapshot]
    public let sourceBundleIdentifier: String?
    public let sourceApplicationName: String?
    public let capturedAt: Date

    public init(changeCount: Int, items: [ClipboardItemSnapshot], sourceBundleIdentifier: String?, sourceApplicationName: String?, capturedAt: Date = .now) {
        self.changeCount = changeCount
        self.items = items
        self.sourceBundleIdentifier = sourceBundleIdentifier
        self.sourceApplicationName = sourceApplicationName
        self.capturedAt = capturedAt
    }
}

public struct ClipboardCapturePolicy: Sendable {
    public var isEnabled: Bool
    public var excludedBundleIdentifiers: Set<String>
    public var maximumRepresentationBytes: Int
    public var excludedTypeIdentifiers: Set<String>
    public var includesTextDrags: Bool

    public init(
        isEnabled: Bool = true,
        excludedBundleIdentifiers: Set<String> = [],
        maximumRepresentationBytes: Int = 32 * 1_024 * 1_024,
        excludedTypeIdentifiers: Set<String> = [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"
        ],
        includesTextDrags: Bool = true
    ) {
        self.isEnabled = isEnabled
        self.excludedBundleIdentifiers = excludedBundleIdentifiers
        self.maximumRepresentationBytes = max(1, maximumRepresentationBytes)
        self.excludedTypeIdentifiers = excludedTypeIdentifiers
        self.includesTextDrags = includesTextDrags
    }

    func rejectsEntireGeneration(containing items: [NSPasteboardItem]) -> Bool {
        let markers = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType"]
        return items.contains { item in item.types.contains { markers.contains($0.rawValue) } }
    }
}

/// Shared by the writer and monitor so self-originated pasteboard generations are never recaptured.
@MainActor
public final class ClipboardWriteRegistry {
    private var pendingChangeCounts: Set<Int> = []
    public init() {}
    func record(_ changeCount: Int) { pendingChangeCounts = [changeCount] }
    func consume(_ changeCount: Int) -> Bool { pendingChangeCounts.remove(changeCount) != nil }
}

/// Main-actor polling adapter. It only emits snapshots when the pasteboard generation changes.
@MainActor
public final class ClipboardMonitor {
    private let pasteboard: NSPasteboard
    private let writeRegistry: ClipboardWriteRegistry
    private let bookmarkAdapter: BookmarkAdapter?
    private var policy: ClipboardCapturePolicy
    private var timer: Timer?
    private var continuation: AsyncStream<ClipboardSnapshot>.Continuation?
    private var lastSeenChangeCount: Int

    public init(pasteboard: NSPasteboard = .general, policy: ClipboardCapturePolicy, writeRegistry: ClipboardWriteRegistry, bookmarkAdapter: BookmarkAdapter? = nil) {
        self.pasteboard = pasteboard
        self.policy = policy
        self.writeRegistry = writeRegistry
        self.bookmarkAdapter = bookmarkAdapter
        self.lastSeenChangeCount = pasteboard.changeCount
    }

    public func update(policy: ClipboardCapturePolicy) { self.policy = policy }

    public func start(pollInterval: TimeInterval = 0.25) -> AsyncStream<ClipboardSnapshot> {
        stop()
        // Clipboard generations are history events; a slow consumer must not silently lose them.
        let (stream, continuation) = AsyncStream<ClipboardSnapshot>.makeStream(bufferingPolicy: .unbounded)
        self.continuation = continuation
        let timer = Timer(timeInterval: max(0.05, pollInterval), repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        continuation.onTermination = { [weak self] _ in
            Task { @MainActor in self?.stop() }
        }
        return stream
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
        continuation?.finish()
        continuation = nil
    }

    /// Register the generation created by the paired content writer.
    public func suppressSelfWrite(changeCount: Int) { writeRegistry.record(changeCount) }

    private func poll() {
        let generation = pasteboard.changeCount
        guard generation != lastSeenChangeCount else { return }
        lastSeenChangeCount = generation
        if writeRegistry.consume(generation) { return }
        guard policy.isEnabled else { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let bundle = app?.bundleIdentifier, policy.excludedBundleIdentifiers.contains(bundle) { return }
        let items = pasteboard.pasteboardItems ?? []
        guard !policy.rejectsEntireGeneration(containing: items) else { return }
        let snapshots = items.compactMap(readItem)
        guard !snapshots.isEmpty else { return }
        continuation?.yield(ClipboardSnapshot(
            changeCount: generation,
            items: snapshots,
            sourceBundleIdentifier: app?.bundleIdentifier,
            sourceApplicationName: app?.localizedName
        ))
    }

    private func readItem(_ item: NSPasteboardItem) -> ClipboardItemSnapshot? {
        let representations = item.types.compactMap { type -> ClipboardRepresentationSnapshot? in
            guard !policy.excludedTypeIdentifiers.contains(type.rawValue),
                  let data = item.data(forType: type),
                  data.count <= policy.maximumRepresentationBytes else { return nil }
            return ClipboardRepresentationSnapshot(typeIdentifier: type.rawValue, data: data)
        }
        let files: [FileReference]
        if let value = item.string(forType: .fileURL), let url = URL(string: value), url.isFileURL {
            files = [FileReference(
                url: url,
                bookmark: try? bookmarkAdapter?.createBookmark(for: url),
                isOwnedCopy: false,
                byteCount: try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize
            )]
        } else {
            files = []
        }
        return representations.isEmpty && files.isEmpty ? nil : ClipboardItemSnapshot(representations: representations, files: files)
    }
}
